"""Audit the shipped atlas against the user's S-52 Symbol Catalogue.

Usage: python ENC/tools/audit_sprites.py --catalogue <Part-I-Addendum.pdf>
Requires PyMuPDF only for this offline documentation task; never at runtime.
The PDF is read locally; canonical references live in Presentation_Library/documents.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re

RESERVED = {
    "CHINFO08": "Mariner information note; no mariner-note model in this viewer",
    "CHINFO09": "Mariner caution note; no mariner-note model in this viewer",
    "CHINFO10": "Manufacturer information note; not an ENC source object",
    "CHINFO11": "Manufacturer caution note; not an ENC source object",
    "DNGHILIT": "Mariner danger highlight; not an ENC source object",
    "OBSTRN02": "Legacy OBSTRN CSP; catalogue p.182 refers to an earlier CSP",
}


def main():
    import pymupdf

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--catalogue", type=Path, required=True)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    atlas = json.loads((root / "Presentation_Library/assets/sprites/day_simplified@2x.json").read_text())
    additions = json.loads((root / "Presentation_Library/assets/sprites/additions.json").read_text(encoding="utf8"))["entries"]
    invalid = {}
    for theme in ("day", "dusk", "night"):
        entries = json.loads((root / f"Presentation_Library/assets/sprites/{theme}_simplified@2x.json").read_text())
        pixmap = pymupdf.Pixmap(root / f"Presentation_Library/assets/sprites/{theme}_simplified@2x.png")
        for name, entry in entries.items():
            if (entry['x'] < 0 or entry['y'] < 0 or entry['width'] <= 0 or entry['height'] <= 0
                    or entry['x'] + entry['width'] > pixmap.width or entry['y'] + entry['height'] > pixmap.height):
                invalid.setdefault(name, []).append(theme)
    for theme in ("dusk", "night"):
        other = json.loads((root / f"Presentation_Library/assets/sprites/{theme}_simplified@2x.json").read_text())
        if set(atlas) != set(other):
            raise ValueError(f"{theme} atlas has different keys")
    source = "\n".join((root / f"Presentation_Library/runtime/{file}").read_text(encoding="utf8")
                       for file in ("sprites.ts", "style.ts", "infrastructure.ts"))
    catalogue = {}
    specifications = {}
    document = pymupdf.open(args.catalogue)
    for page_index, page in enumerate(document):
        text = page.get_text()
        match = re.search(r"(?:Symbol|Pattern|Linestyle) Name:\s*(SY|AP|LC)\(([^)]+)\)", text)
        if match:
            key = (match[1], match[2].strip())
            catalogue[key] = page_index + 1
            fields = {
                "pivotColumnMm": r"Pivot Point Column:\s*(-?[\d.]+)",
                "pivotRowMm": r"Pivot Point Row:\s*(-?[\d.]+)",
                "widthMm": r"Width of Bounding Box:\s*([\d.]+)",
                "heightMm": r"Height of Bounding Box:\s*([\d.]+)",
            }
            spec = {}
            for field, pattern in fields.items():
                value = re.search(pattern, text)
                if value:
                    number = float(value[1])
                    if field.startswith("pivot") or number > 0:
                        spec[field] = number
            weight = re.search(r"(?:outline|symbol|line) weight\s*([\d.]+)\s*mm", text, re.I)
            if weight:
                spec["lineWeightMm"] = float(weight[1])
            if spec:
                specifications[key] = spec
    rows = []
    referenced = 0
    for name in sorted(atlas):
        used = f"'{name}'" in source or f'"{name}"' in source
        if not used and name not in RESERVED and name not in additions:
            raise ValueError(f"Unaccounted sprite: {name}")
        if used and name in RESERVED:
            raise ValueError(f"Review reserved sprite now referenced: {name}")
        referenced += used
        info = additions.get(name)
        kind, symbol = (info['kind'],info['symbol']) if info else (("AP", name[:-1]) if name.endswith("P") else ("SY", name))
        page = catalogue.get((kind, symbol))
        reference = f"{kind}({symbol}), p.{page - 6} / PDF {page}" if page else "Not found in supplied 4.0(.3) catalogue; retained atlas asset"
        status = "Referenced by portrayal" if used else RESERVED.get(name,"Available in expanded atlas; selector not yet implemented")
        if info and info.get('kind')=='LC':
            status += "; viewer line texture (not a full LC interpreter)"
        if name in invalid:
            status += "; **INVALID atlas rectangle** in " + ", ".join(invalid[name])
        rows.append(f"| `{name}` | {status} | {reference} |")
    header = ("# Sprite inventory\n\n"
              f"Atlas: {len(atlas)} images per theme. Runtime references: {referenced}.\n\n"
              "Generated by `ENC/tools/audit_sprites.py` from the supplied S-52 PresLib "
              "4.0(.3) Part I Addendum (December 2020). `P` suffixes in atlas keys "
              "identify AP patterns; SY and LC names are separate catalogue entries.\n\n"
              "A reference means a selector/layer exists; it does not mean the dataset "
              "contains that condition or that the entire S-52 CSP is implemented. "
              "Invalid image rectangles are reported independently of key existence. "
              "Assets absent from this edition are explicitly marked.\n\n"
              "| Sprite | Runtime status | Catalogue reference |\n|---|---|---|\n")
    (root / "Presentation_Library/reports/SPRITE-INVENTORY.md").write_text(header + "\n".join(rows) + "\n", encoding="utf8")

    # Exact catalogue pivot and physical box dimensions let the renderer size
    # and place each native symbol at the standard 96 CSS dpi. Keep this small
    # generated data file separate from the image atlas and source catalogue.
    generated = {}
    for name in sorted(atlas):
        info = additions.get(name)
        kind, symbol = (info["kind"], info["symbol"]) if info else (("AP", name[:-1]) if name.endswith("P") else ("SY", name))
        spec = specifications.get((kind, symbol))
        if spec:
            entry = atlas[name]
            generated[name] = {
                **spec,
                "kind": kind,
                "symbol": symbol,
                "imageWidthPx": entry["width"],
                "imageHeightPx": entry["height"],
                "pixelRatio": entry["pixelRatio"],
            }
    target = root / "Presentation_Library/runtime/spriteSpecs.generated.ts"
    target.write_text(
        "// Generated by ENC/tools/audit_sprites.py from the supplied S-52 Symbol Catalogue.\n"
        "// Values are millimetres from the catalogue; runtime converts them to CSS pixels.\n"
        "export type SpriteSpec = { kind: string; symbol: string; pivotColumnMm?: number; pivotRowMm?: number; widthMm?: number; heightMm?: number; lineWeightMm?: number; imageWidthPx: number; imageHeightPx: number; pixelRatio: number };\n"
        "export const spriteSpecs: Record<string, SpriteSpec> = "
        + json.dumps(generated, ensure_ascii=False, indent=2)
        + " as const;\n",
        encoding="utf8",
    )
    print(f"{len(atlas)} sprites audited across 3 themes; {referenced} runtime references; {len(atlas)-referenced} available/reserved")
    symbol_specs = [row for row in generated.values() if row["kind"] == "SY"]
    sized_symbols = sum("widthMm" in row and "heightMm" in row for row in symbol_specs)
    print(f"Wrote pivots for {sum('pivotColumnMm' in row for row in symbol_specs)} symbols and physical dimensions for {sized_symbols} to {target.relative_to(root)}")
    for name, themes in invalid.items():
        print(f"INVALID atlas rectangle: {name} ({', '.join(themes)}); key existence does not imply a usable image")


if __name__ == "__main__":
    main()
